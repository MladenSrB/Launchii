/** A 24×24 path-data mark drawn at [sizePx] in [color] (even-odd, so counters punch through). */
class MarkDrawable(pathData: String, color: Int, private val sizePx: Int) : Drawable() {
    private val source: Path = PathParser.createPathFromPathData(pathData).apply { fillType = Path.FillType.EVEN_ODD }
    private val path = Path()
    private val m = Matrix()
    private val p = Paint(Paint.ANTI_ALIAS_FLAG).apply { this.color = color }

    override fun onBoundsChange(bounds: android.graphics.Rect) {
        m.setScale(bounds.width() / 24f, bounds.height() / 24f)
        m.postTranslate(bounds.left.toFloat(), bounds.top.toFloat())
        source.transform(m, path)
        path.fillType = Path.FillType.EVEN_ODD
    }

    override fun draw(canvas: Canvas) = canvas.drawPath(path, p)
    override fun getIntrinsicWidth() = sizePx
    override fun getIntrinsicHeight() = sizePx
    override fun setAlpha(alpha: Int) { p.alpha = alpha }
    override fun setColorFilter(cf: ColorFilter?) { p.colorFilter = cf }
    @Deprecated("Deprecated in Java")
    override fun getOpacity() = PixelFormat.TRANSLUCENT
}
